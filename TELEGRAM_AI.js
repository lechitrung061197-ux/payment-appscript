function payTgVerifyWebhookKey_(e) {
  const saved = String(PropertiesService.getScriptProperties().getProperty(TELEGRAM_AI_CFG.PROP_WEBHOOK_SECRET) || '').trim();
  if (!saved) return false;
  const supplied = e && e.parameter ? String(e.parameter.key || '') : '';
  return supplied === saved;
}

function payTgIsDuplicateUpdate_(updateId) {
  const props = PropertiesService.getScriptProperties();
  const last = Number(props.getProperty(TELEGRAM_AI_CFG.PROP_LAST_UPDATE) || -1);
  const current = Number(updateId);
  if (isFinite(last) && current <= last) return true;
  props.setProperty(TELEGRAM_AI_CFG.PROP_LAST_UPDATE, String(current));
  return false;
}

function payTgSendMessage_(chatId, text) {
  const props = PropertiesService.getScriptProperties();
  const token = String(props.getProperty(TELEGRAM_AI_CFG.PROP_TELEGRAM_TOKEN) || '').trim();
  if (!token) throw new Error('TELEGRAM_BOT_TOKEN is missing in Script Properties.');

  const res = UrlFetchApp.fetch(TELEGRAM_AI_CFG.TELEGRAM_API_BASE + encodeURIComponent(token) + '/sendMessage', {
    method: 'post',
    contentType: 'application/json',
    payload: JSON.stringify({ chat_id: String(chatId), text: String(text || ''), disable_web_page_preview: true }),
    muteHttpExceptions: true
  });

  const code = res.getResponseCode();
  if (code < 200 || code >= 300) throw new Error('Telegram sendMessage HTTP ' + code + ': ' + res.getContentText().slice(0, 700));
}

function payTgSendLongMessage_(chatId, text) {
  const s = String(text || '');
  if (s.length <= TELEGRAM_AI_CFG.TELEGRAM_MAX_MESSAGE) {
    payTgSendMessage_(chatId, s);
    return;
  }

  let remaining = s;
  while (remaining.length) {
    let cut = Math.min(TELEGRAM_AI_CFG.TELEGRAM_MAX_MESSAGE, remaining.length);
    if (cut < remaining.length) {
      const nl = remaining.lastIndexOf('\n', cut);
      if (nl > cut * 0.6) cut = nl;
    }
    payTgSendMessage_(chatId, remaining.slice(0, cut));
    remaining = remaining.slice(cut).replace(/^\s+/, '');
  }
}

function payTgPrettyJson_(obj) {
  try { return JSON.stringify(obj, null, 2); } catch (_) { return String(obj); }
}



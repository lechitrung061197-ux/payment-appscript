function payAiOpenAiRequest_(payload) {
  const props = PropertiesService.getScriptProperties();
  const key = String(props.getProperty(TELEGRAM_AI_CFG.PROP_OPENAI_KEY) || '').trim();
  if (!key) throw new Error('OPENAI_API_KEY is missing in Script Properties.');

  const res = UrlFetchApp.fetch(TELEGRAM_AI_CFG.OPENAI_URL, {
    method: 'post',
    contentType: 'application/json',
    headers: { Authorization: 'Bearer ' + key },
    payload: JSON.stringify(payload),
    muteHttpExceptions: true
  });

  const code = res.getResponseCode();
  const text = res.getContentText();
  let json = null;
  try { json = JSON.parse(text); } catch (_) {}

  if (code < 200 || code >= 300) {
    const detail = json && json.error && json.error.message ? json.error.message : text.slice(0, 1200);
    throw new Error('OpenAI API HTTP ' + code + ': ' + detail);
  }
  return json;
}

function payAiExtractFunctionCalls_(response) {
  const out = response && Array.isArray(response.output) ? response.output : [];
  return out.filter(function(item) { return item && item.type === 'function_call' && item.name && item.call_id; });
}

function payAiExtractOutputText_(response) {
  const out = response && Array.isArray(response.output) ? response.output : [];
  const parts = [];
  out.forEach(function(item) {
    if (!item || item.type !== 'message' || !Array.isArray(item.content)) return;
    item.content.forEach(function(c) {
      if (c && c.type === 'output_text' && c.text) parts.push(String(c.text));
    });
  });
  return parts.join('\n').trim();
}

function payAiResetConversation_(chatId) {
  PropertiesService.getScriptProperties().deleteProperty(TELEGRAM_AI_CFG.RESPONSE_PREFIX + String(chatId));
}



/**
 * ============================================================================
 * TELEGRAM_AI.GS — PAYMENT ALL TELEGRAM + OPENAI AGENT
 * ============================================================================
 * Telegram is the remote interface. The AI can read/aggregate/search the
 * Payment All workbook through AI_GATEWAY.gs and can call approved actions.
 *
 * Secrets are stored in Script Properties, NOT in sheets/code:
 *   OPENAI_API_KEY
 *   OPENAI_MODEL                  (optional; default gpt-5.6)
 *   TELEGRAM_BOT_TOKEN
 *   TELEGRAM_ALLOWED_USER_ID      (recommended; can be blank during /whoami setup)
 *   TELEGRAM_WEBHOOK_SECRET       (auto-generated by setupPaymentAi)
 *   PAYMENT_SPREADSHEET_ID        (auto-captured by setupPaymentAi)
 *   PAYMENT_ACTION_PIN_HASH       (set by setPaymentAiActionPin)
 *
 * Telegram PIN messages are intercepted locally and NEVER sent to OpenAI.
 * ============================================================================
 */

const TELEGRAM_AI_CFG = Object.freeze({
  OPENAI_URL: 'https://api.openai.com/v1/responses',
  OPENAI_MODEL_DEFAULT: 'gpt-5.6',
  MAX_AGENT_TOOL_ROUNDS: 8,
  MAX_REPEAT_SAME_TOOL_CALL: 2,
  MAX_OUTPUT_TOKENS: 2500,
  TELEGRAM_API_BASE: 'https://api.telegram.org/bot',
  TELEGRAM_MAX_MESSAGE: 3900,

  PROP_OPENAI_KEY: 'OPENAI_API_KEY',
  PROP_OPENAI_MODEL: 'OPENAI_MODEL',
  PROP_TELEGRAM_TOKEN: 'TELEGRAM_BOT_TOKEN',
  PROP_ALLOWED_USER: 'TELEGRAM_ALLOWED_USER_ID',
  PROP_WEBHOOK_SECRET: 'TELEGRAM_WEBHOOK_SECRET',
  PROP_WEB_APP_URL: 'TELEGRAM_WEB_APP_URL',
  PROP_LAST_UPDATE: 'TELEGRAM_LAST_UPDATE_ID',
  RESPONSE_PREFIX: 'PAYMENT_AI_RESPONSE_ID_',
  PROP_SPREADSHEET_ID: 'PAYMENT_SPREADSHEET_ID'
});


/************************* WEB APP *************************/

function doGet() {
  return HtmlService.createHtmlOutput('Payment AI Telegram webhook is alive.');
}

function doPost(e) {
  try {
    if (!payTgVerifyWebhookKey_(e)) return HtmlService.createHtmlOutput('forbidden');

    const body = e && e.postData && e.postData.contents ? e.postData.contents : '{}';
    const update = JSON.parse(body);
    if (!update || update.update_id === undefined) return HtmlService.createHtmlOutput('ok');

    if (payTgIsDuplicateUpdate_(update.update_id)) return HtmlService.createHtmlOutput('ok');

    const msg = update.message || update.edited_message;
    if (!msg || !msg.chat || !msg.from) return HtmlService.createHtmlOutput('ok');

    const chatId = String(msg.chat.id);
    const userId = String(msg.from.id);
    const text = String(msg.text || '').trim();

    const allowed = String(PropertiesService.getScriptProperties().getProperty(TELEGRAM_AI_CFG.PROP_ALLOWED_USER) || '').trim();
    if (!allowed) {
      payTgSendMessage_(chatId, 'Your Telegram User ID: ' + userId + '\n\nSet Script Property TELEGRAM_ALLOWED_USER_ID = ' + userId + ' to lock this bot to your account.');
      return HtmlService.createHtmlOutput('ok');
    }

    if (allowed !== userId) return HtmlService.createHtmlOutput('ok');
    if (!text) {
      payTgSendMessage_(chatId, 'Hiện tại bot xử lý tin nhắn text.');
      return HtmlService.createHtmlOutput('ok');
    }

    payTgHandleText_(chatId, userId, text);
    return HtmlService.createHtmlOutput('ok');
  } catch (err) {
    try {
      const raw = e && e.postData && e.postData.contents ? JSON.parse(e.postData.contents) : null;
      const chatId = raw && raw.message && raw.message.chat ? String(raw.message.chat.id) : '';
      if (chatId) payTgSendMessage_(chatId, '❌ Error: ' + (err && err.message ? err.message : String(err)));
    } catch (_) {}
    return HtmlService.createHtmlOutput('ok');
  }
}

function payTgHandleText_(chatId, userId, text) {
  if (/^\/start\b/i.test(text) || /^\/help\b/i.test(text)) {
    payTgSendMessage_(chatId,
      'Payment AI ready.\n\n' +
      'Hỏi tự nhiên, ví dụ:\n' +
      '• CUS001 còn bao nhiêu chưa invoice?\n' +
      '• PayPal withdrawal nào chưa match?\n' +
      '• Tổng PayPal fee tháng này?\n' +
      '• Preview invoice CUS002 16/08/2026 tới 26/08/2026\n\n' +
      'Lệnh local:\n' +
      '/reset — reset ngữ cảnh AI\n' +
      '/cancel — hủy action đang chờ PIN\n' +
      '/pin 123456 — xác nhận protected action\n' +
      '/whoami — xem Telegram User ID'
    );
    return;
  }

  if (/^\/whoami\b/i.test(text)) {
    payTgSendMessage_(chatId, 'Telegram User ID: ' + userId + '\nChat ID: ' + chatId);
    return;
  }

  if (/^\/reset\b/i.test(text)) {
    payAiResetConversation_(chatId);
    payAiCancelPendingAction_(chatId);
    payTgSendMessage_(chatId, '✓ Đã reset ngữ cảnh AI và hủy pending action.');
    return;
  }

  if (/^\/cancel\b/i.test(text)) {
    payAiCancelPendingAction_(chatId);
    payTgSendMessage_(chatId, '✓ Đã hủy protected action đang chờ.');
    return;
  }

  const pinMatch = text.match(/^\/pin\s+(.+)$/i);
  if (pinMatch) {
    const result = payAiExecutePendingAction_(chatId, pinMatch[1].trim());
    if (result.ok) {
      payTgSendMessage_(chatId, '✅ Protected action completed.\n' + payTgPrettyJson_(result.result));
      // Financial state changed; reset model context so next question starts from fresh data.
      payAiResetConversation_(chatId);
    } else {
      payTgSendMessage_(chatId, '❌ ' + result.error);
    }
    return;
  }

  if (/^\/pin\b/i.test(text)) {
    payTgSendMessage_(chatId, 'Dùng: /pin <ACTION_PIN>');
    return;
  }

  const answer = payAiAskOpenAI_(chatId, text);
  payTgSendLongMessage_(chatId, answer);
}


/************************* OPENAI AGENT *************************/

function payAiAskOpenAI_(chatId, userText) {
  const props = PropertiesService.getScriptProperties();
  const model = String(props.getProperty(TELEGRAM_AI_CFG.PROP_OPENAI_MODEL) || TELEGRAM_AI_CFG.OPENAI_MODEL_DEFAULT).trim();
  const previousId = String(props.getProperty(TELEGRAM_AI_CFG.RESPONSE_PREFIX + chatId) || '').trim();

  const instructions = payAiBuildInstructions_();
  const tools = payAiToolDefinitions_();
  let response;

  const firstPayload = {
    model: model,
    instructions: instructions,
    input: String(userText || ''),
    tools: tools,
    tool_choice: 'auto',
    parallel_tool_calls: false,
    max_output_tokens: TELEGRAM_AI_CFG.MAX_OUTPUT_TOKENS,
    store: true
  };
  if (previousId) firstPayload.previous_response_id = previousId;

  try {
    response = payAiOpenAiRequest_(firstPayload);
  } catch (err) {
    // A stale/expired previous response should not make the bot unusable.
    if (previousId) {
      props.deleteProperty(TELEGRAM_AI_CFG.RESPONSE_PREFIX + chatId);
      delete firstPayload.previous_response_id;
      response = payAiOpenAiRequest_(firstPayload);
    } else {
      throw err;
    }
  }

  let rounds = 0;
  const seenCalls = {};

  while (rounds < TELEGRAM_AI_CFG.MAX_AGENT_TOOL_ROUNDS) {
    const calls = payAiExtractFunctionCalls_(response);
    if (!calls.length) break;

    console.log(
      'Payment AI tool round ' + (rounds + 1) + '/' + TELEGRAM_AI_CFG.MAX_AGENT_TOOL_ROUNDS + ': ' +
      calls.map(function(c) { return c.name; }).join(', ')
    );

    const outputs = calls.map(function(call) {
      let args = {};
      try { args = call.arguments ? JSON.parse(call.arguments) : {}; }
      catch (_) { args = {}; }

      // Stop the model from burning rounds by repeating the exact same read.
      const signature = call.name + '|' + JSON.stringify(args);
      seenCalls[signature] = Number(seenCalls[signature] || 0) + 1;

      let result;
      if (seenCalls[signature] > TELEGRAM_AI_CFG.MAX_REPEAT_SAME_TOOL_CALL) {
        result = {
          ok: false,
          error: 'Repeated identical tool call blocked. Use the data already returned and answer the user; do not request the same call again.'
        };
      } else {
        result = payAiDispatchTool_(call.name, args, { chatId: chatId, channel: 'telegram' });
      }

      let output = JSON.stringify(result);
      if (output.length > PAYMENT_AI_CFG.MAX_TOOL_OUTPUT_CHARS) {
        output = JSON.stringify({
          ok: false,
          error: 'Tool output too large. Use narrower filters, aggregate_sheet, selected columns, or pagination.'
        });
      }

      return { type: 'function_call_output', call_id: call.call_id, output: output };
    });

    const nextRound = rounds + 1;
    const forceFinalAnswer = nextRound >= TELEGRAM_AI_CFG.MAX_AGENT_TOOL_ROUNDS;

    response = payAiOpenAiRequest_({
      model: model,
      instructions: instructions + (forceFinalAnswer
        ? '\n\nFINAL TOOL BUDGET RULE: You have used the maximum tool budget for this user message. You MUST answer now using the information already gathered. Do not call another tool. If some data is still missing, clearly say what is missing instead of requesting another tool.'
        : ''),
      previous_response_id: response.id,
      input: outputs,
      tools: tools,
      tool_choice: forceFinalAnswer ? 'none' : 'auto',
      parallel_tool_calls: false,
      max_output_tokens: TELEGRAM_AI_CFG.MAX_OUTPUT_TOKENS,
      store: true
    });

    rounds = nextRound;
  }

  if (response && response.id) {
    props.setProperty(TELEGRAM_AI_CFG.RESPONSE_PREFIX + chatId, response.id);
  }

  const text = payAiExtractOutputText_(response);
  if (text) return text;

  // This should now be rare because the last round is forced to text-only.
  return 'AI chưa tạo được câu trả lời từ dữ liệu đã đọc. Gõ /reset rồi hỏi lại câu đó; nếu vẫn lỗi, xem Execution log để biết tool nào đang lặp.';
}


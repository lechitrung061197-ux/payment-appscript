/** Run AFTER setTelegramWebAppUrl(). */
function setTelegramWebhook() {
  const props = PropertiesService.getScriptProperties();
  const token = String(props.getProperty(TELEGRAM_AI_CFG.PROP_TELEGRAM_TOKEN) || '').trim();
  const secret = String(props.getProperty(TELEGRAM_AI_CFG.PROP_WEBHOOK_SECRET) || '').trim();
  if (!token) throw new Error('TELEGRAM_BOT_TOKEN is missing.');
  if (!secret) throw new Error('TELEGRAM_WEBHOOK_SECRET is missing. Run setupPaymentAi().');

  let serviceUrl = String(props.getProperty(TELEGRAM_AI_CFG.PROP_WEB_APP_URL) || '').trim();

  // Fallback only when no explicit URL is saved. Never accept a /dev URL.
  if (!serviceUrl) {
    serviceUrl = String(ScriptApp.getService().getUrl() || '').trim();
    if (!serviceUrl || /\/dev(?:$|[?#])/.test(serviceUrl)) {
      throw new Error('Production Web App URL is not saved. Run setTelegramWebAppUrl() and paste the URL ending in /exec.');
    }
  }

  serviceUrl = payTgNormalizeExecUrl_(serviceUrl);
  props.setProperty(TELEGRAM_AI_CFG.PROP_WEB_APP_URL, serviceUrl);

  const webhookUrl = serviceUrl + '?key=' + encodeURIComponent(secret);

  const res = UrlFetchApp.fetch(TELEGRAM_AI_CFG.TELEGRAM_API_BASE + encodeURIComponent(token) + '/setWebhook', {
    method: 'post',
    contentType: 'application/json',
    payload: JSON.stringify({
      url: webhookUrl,
      allowed_updates: ['message', 'edited_message'],
      drop_pending_updates: true
    }),
    muteHttpExceptions: true
  });

  const code = res.getResponseCode();
  const text = res.getContentText();
  if (code < 200 || code >= 300) throw new Error('Telegram setWebhook HTTP ' + code + ': ' + text);
  Logger.log('Webhook URL: ' + serviceUrl);
  Logger.log(text);
  return JSON.parse(text);
}


function payTgNormalizeExecUrl_(value) {
  let url = String(value || '').trim();
  if (!url) throw new Error('Web App URL is empty.');
  url = url.split('#')[0].split('?')[0].replace(/\/+$/, '');
  if (/\/dev$/i.test(url)) {
    throw new Error('This is a /dev Test deployment URL. Copy the deployed Web App URL ending in /exec.');
  }
  if (!/\/exec$/i.test(url)) {
    throw new Error('Invalid Web App URL. It must end in /exec.');
  }
  return url;
}


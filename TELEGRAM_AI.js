/** Run once from the bound Payment All spreadsheet. */
function setupPaymentAi() {
  const ss = SpreadsheetApp.getActive();
  if (!ss) throw new Error('Open the Payment All spreadsheet and run setupPaymentAi() from its bound Apps Script project.');

  const props = PropertiesService.getScriptProperties();
  props.setProperty(TELEGRAM_AI_CFG.PROP_SPREADSHEET_ID, ss.getId());
  if (!props.getProperty(TELEGRAM_AI_CFG.PROP_OPENAI_MODEL)) props.setProperty(TELEGRAM_AI_CFG.PROP_OPENAI_MODEL, TELEGRAM_AI_CFG.OPENAI_MODEL_DEFAULT);
  if (!props.getProperty(TELEGRAM_AI_CFG.PROP_WEBHOOK_SECRET)) props.setProperty(TELEGRAM_AI_CFG.PROP_WEBHOOK_SECRET, payTgRandomSecret_());

  SpreadsheetApp.getUi().alert(
    'Payment AI base setup complete.\n\n' +
    'Now add Script Properties:\n' +
    'OPENAI_API_KEY\n' +
    'TELEGRAM_BOT_TOKEN\n' +
    'TELEGRAM_ALLOWED_USER_ID (can leave blank initially)\n\n' +
    'Then deploy as Web App, run setTelegramWebAppUrl(), then setTelegramWebhook().\n' +
    'Run setPaymentAiActionPin() to create the separate action PIN.'
  );
}

/** Sets a separate action PIN as SHA-256 hash. Do NOT use a Google/PayPal password here. */
function setPaymentAiActionPin() {
  const ui = SpreadsheetApp.getUi();
  const r = ui.prompt('Payment AI Action PIN', 'Enter a NEW separate PIN for protected actions. Do not reuse Google/PayPal/OpenAI/Telegram passwords.', ui.ButtonSet.OK_CANCEL);
  if (r.getSelectedButton() !== ui.Button.OK) return;
  const pin = String(r.getResponseText() || '').trim();
  if (pin.length < 4) throw new Error('Use at least 4 characters for the action PIN.');
  PropertiesService.getScriptProperties().setProperty(PAYMENT_AI_CFG.PROP_ACTION_PIN_HASH, payAiSha256Hex_(pin));
  ui.alert('Action PIN saved as SHA-256 hash.');
}

